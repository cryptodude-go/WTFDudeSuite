[CmdletBinding()]
param(
    [string]$AddonPath = (Split-Path -Parent $PSScriptRoot)
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$repository = 'cryptodude-go/WTFDudeSuite'
$addonRoot = (Resolve-Path -LiteralPath $AddonPath).Path
$tocPath = Join-Path $addonRoot 'WTFDudeSuite.toc'
$cachePath = Join-Path $addonRoot 'Core\ReleaseInfo.lua'

function ConvertTo-ReleaseVersion([string]$Text) {
    if ($Text -notmatch '^v?(\d+\.\d+(?:\.\d+){0,2})$') {
        throw "Unsupported release version '$Text'. Use a numeric version such as v1.8.1."
    }
    $clean = $Matches[1]
    foreach ($part in $clean.Split('.')) {
        if ([int]$part -gt 99999) { throw 'Version component is too large.' }
    }
    return $clean
}

$toc = Get-Content -LiteralPath $tocPath -Raw
if ($toc -notmatch '(?m)^## Version:\s*(\S+)\s*$') { throw 'Installed version is missing.' }
$localVersion = ConvertTo-ReleaseVersion $Matches[1]
$headers = @{ 'User-Agent' = 'WTF-DUDE-SUITE-VersionCheck'; 'Accept' = 'application/vnd.github+json' }
$remoteVersion = $null
$source = 'GitHub release'
try {
    $release = Invoke-RestMethod -Uri "https://api.github.com/repos/$repository/releases/latest" -Headers $headers -TimeoutSec 12
    if (-not $release.draft -and -not $release.prerelease) {
        $remoteVersion = ConvertTo-ReleaseVersion $release.tag_name
    }
} catch {
    # A repository without releases can publish its version through the main TOC.
    $source = 'GitHub main branch'
}
if (-not $remoteVersion) {
    $source = 'GitHub main branch'
    $remoteToc = (Invoke-WebRequest -UseBasicParsing -Uri "https://raw.githubusercontent.com/$repository/main/WTFDudeSuite.toc" -Headers $headers -TimeoutSec 12).Content
    if ($remoteToc -notmatch '(?m)^## Version:\s*(\S+)\s*$') { throw 'GitHub version is missing.' }
    $remoteVersion = ConvertTo-ReleaseVersion $Matches[1]
}

function ConvertTo-Comparable([string]$Text) {
    $parts = $Text.Split('.')
    while ($parts.Count -lt 4) { $parts += '0' }
    return [version]($parts -join '.')
}
$newer = (ConvertTo-Comparable $remoteVersion) -gt (ConvertTo-Comparable $localVersion)
$cache = "-- Optional GitHub-check result, generated by Tools/Check-GitHub.ps1.`nlocal _, HP = ...`nHP.releaseInfo = {}`n"
if ($newer) {
    # Only validated numeric version text is written as data. No remote code is loaded.
    $cache = "-- GitHub version check result. Loaded on the next login or reload.`nlocal _, HP = ...`nHP.releaseInfo = { repository = `"$repository`", version = `"$remoteVersion`" }`n"
}
$existing = if (Test-Path -LiteralPath $cachePath) { [IO.File]::ReadAllText($cachePath).Replace("`r`n", "`n") } else { '' }
if ($existing -ne $cache) {
    $temporaryPath = "$cachePath.tmp"
    [IO.File]::WriteAllText($temporaryPath, $cache, (New-Object Text.UTF8Encoding($false)))
    Move-Item -LiteralPath $temporaryPath -Destination $cachePath -Force
}
[pscustomobject]@{
    Installed = $localVersion
    GitHub = $remoteVersion
    Source = $source
    UpdateAvailable = $newer
}
